export function createMockAnswer(prompt) {
  const subject = prompt.replace(/[?!.]+$/g, '').trim();

  if (/폴더|파일/.test(prompt)) {
    return `좋아요. **${subject}**를 기준으로 찾기 쉽고 확장하기 편한 구조를 제안해 드릴게요.\n\n1. 목적별로 최상위 폴더를 나눕니다.\n2. 파일명은 날짜보다 내용 중심으로 통일합니다.\n3. 완료된 자료는 archive 폴더로 이동합니다.\n\n예를 들면 “진행 중 / 공유 자료 / 완료”의 세 단계로 시작하면 관리 부담이 적습니다. 원하시면 실제 파일 목록에 맞춰 더 구체적으로 정리해 드릴까요?`;
  }

  if (/업무|업데이트|변경/.test(prompt)) {
    return `요청하신 **${subject}**를 실무 관점에서 간단히 정리했습니다.\n\n• 가장 먼저 확인할 부분은 일정과 담당자 변경입니다.\n• 진행 중인 업무는 우선순위와 마감일을 함께 표시하는 것이 좋습니다.\n• 공유가 필요한 변경점은 영향 범위와 다음 액션까지 한 줄로 덧붙여 주세요.\n\n현재는 목업 답변이며, 실제 사내 데이터가 연결되면 관련 문서와 최근 변경 이력을 함께 보여줄 수 있습니다.`;
  }

  if (/이메일|메일/.test(prompt)) {
    return `이메일을 정리할 때는 **발신 빈도, 최근 열람 여부, 구독 해지 링크 유무**를 기준으로 확인하면 빠릅니다.\n\n우선 광고·뉴스레터 유형부터 모은 뒤 최근 90일간 열어보지 않은 메일을 추려보세요. 중요한 알림 메일이 섞이지 않도록 결제, 보안, 계정 관련 발신자는 제외하는 것을 권장합니다.\n\n실제 메일 연결 시 구독 취소 후보를 목록으로 정리해 드릴 수 있어요.`;
  }

  return `**${subject}**에 대해 함께 정리해 볼게요.\n\n먼저 목표를 한 문장으로 정한 다음, 필요한 정보를 작은 단위로 나누는 것이 좋습니다. 그다음 중요도와 실행 순서를 기준으로 정리하면 바로 활용할 수 있는 결과를 만들 수 있어요.\n\n원하시면 제가 초안, 체크리스트, 또는 단계별 실행 계획 중 원하는 형태로 더 구체화해 드릴게요.`;
}
